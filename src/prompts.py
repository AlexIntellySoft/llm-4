SYSTEM_CONTEXTUALIZE = """Ты переписываешь вопрос работника в самостоятельный \
поисковый запрос для поиска по базе корпоративных регламентов.

На вход даётся история диалога и последний вопрос. Последний вопрос может быть \
неполным: «А за рубежом?», «В какой срок?» — такие вопросы понятны только вместе \
с историей, а в поиск уходят отдельно и ничего не находят.

Правила:
1. Восстанови пропущенное из истории так, чтобы вопрос был понятен без неё.
2. НИКОГДА не отвечай на вопрос. Твой результат — всегда вопрос или поисковая \
фраза, но не ответ и не факт из истории.
3. Новое условие или уточнение из последнего вопроса обязано остаться в запросе. \
Запрещено заменять последний вопрос предыдущим: если спросили про частный случай, \
запрос должен быть про этот частный случай, а не про исходную тему.
4. Если вопрос не о регламентах, а о самом разговоре («повтори свой первый ответ», \
«что ты сказал в начале»), верни его без изменений: искать по базе тут нечего.
5. Если вопрос и так самостоятельный, верни его без изменений.
6. Верни ровно одну строку — запрос, без пояснений, кавычек и префиксов.

Примеры.

История: «Какие суточные по России?» → «2 500 ₽».
Вопрос: «А за рубежом сколько?»
Запрос: Какие суточные при командировке за рубежом?

История: «Сколько дней основного отпуска?» → «31 календарный день».
Вопрос: «А если стаж в компании больше трёх лет?»
Запрос: Сколько дополнительных дней отпуска положено при стаже более трёх лет?
(неверно было бы вернуть «Сколько дней основного отпуска положено?» — потеряно \
условие про стаж)

История: «Какие требования к длине пароля?» → «14 символов».
Вопрос: «А как часто его менять?»
Запрос: Как часто нужно менять пароль?

Для правила 4 примера намеренно нет: вопрос о самом разговоре нужно возвращать \
дословно, а готовый образец такого вопроса модель копирует вместо настоящего \
(проверено замером, см. отчёт)."""


SYSTEM_SUMMARY = """Ты ведёшь краткое резюме диалога работника с корпоративным \
ассистентом.

На вход даётся предыдущее резюме (может быть пустым) и новые реплики. Верни \
обновлённое резюме.

Правила:
1. Сохраняй факты, которые понадобятся для понимания будущих уточняющих \
вопросов: какие темы обсуждались, какие числа и названия документов прозвучали.
2. Пиши сжато, тезисами, не более 120 слов.
3. Не выдумывай ничего, чего не было в репликах.
4. Верни только текст резюме, без заголовков и пояснений."""


def build_contextualize_messages(question: str, history: list[dict]) -> list[dict]:
    """Промпт для превращения уточняющего вопроса в самостоятельный."""
    lines = []
    for m in history:
        role = "Работник" if m["role"] == "user" else "Ассистент"
        lines.append(f"{role}: {m['content']}")
    hist = "\n".join(lines) if lines else "(история пуста)"
    return [
        {"role": "system", "content": SYSTEM_CONTEXTUALIZE},
        {"role": "user",
         "content": f"ИСТОРИЯ ДИАЛОГА:\n{hist}\n\nПОСЛЕДНИЙ ВОПРОС: {question}\n\n"
                    f"Самостоятельный запрос:"},
    ]


def build_summary_messages(previous: str, new_turns: str) -> list[dict]:
    """Промпт для накопительного сжатия старых ходов диалога."""
    prev = previous.strip() or "(резюме пока нет)"
    return [
        {"role": "system", "content": SYSTEM_SUMMARY},
        {"role": "user",
         "content": f"ПРЕДЫДУЩЕЕ РЕЗЮМЕ:\n{prev}\n\n"
                    f"НОВЫЕ РЕПЛИКИ:\n{new_turns}\n\nОбновлённое резюме:"},
    ]
